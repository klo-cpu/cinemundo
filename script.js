function obterCotaClubeDisponivel() {
  const assinatura = obterAssinaturaClube();
  if (!assinatura) return null;
  const regra = regrasPlanosClube[assinatura.plano] || regrasPlanosClube.Gold;
  const mes = chaveMesAtual();
  const usados = obterHistoricoUsuario()
    .filter(p => p.mesRef === mes)
    .reduce((soma, p) => soma + (p.cortesiasClubeUsadas || 0), 0);

  return {
    plano: assinatura.plano,
    total: regra.cotaMensal,
    usados,
    restantes: Math.max(0, regra.cotaMensal - usados),
    formatos: regra.formatos
  };
}

