function desenharQRCodeSimulado(canvas, textoCodificado) {
  const ctx = canvas.getContext("2d");
  const size = canvas.width;
  ctx.fillStyle = "#ffffff";
  ctx.fillRect(0, 0, size, size);

  const grid = 21;
  const cell = Math.floor(size / grid);
  let hash = 2166136261;
  for (let i = 0; i < textoCodificado.length; i++) {
    hash ^= textoCodificado.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }

  ctx.fillStyle = "#0b0c10";
  for (let r = 0; r < grid; r++) {
    for (let c = 0; c < grid; c++) {
      const emCantoSuperiorEsq = r < 7 && c < 7;
      const emCantoSuperiorDir = r < 7 && c >= grid - 7;
      const emCantoInferiorEsq = r >= grid - 7 && c < 7;

      let preencher = false;
      if (emCantoSuperiorEsq || emCantoSuperiorDir || emCantoInferiorEsq) {
        const lr = r >= grid - 7 ? r - (grid - 7) : r;
        const lc = c >= grid - 7 ? c - (grid - 7) : c;
        const bordaExterna = lr === 0 || lr === 6 || lc === 0 || lc === 6;
        const centro = lr >= 2 && lr <= 4 && lc >= 2 && lc <= 4;
        preencher = bordaExterna || centro;
      } else {
        const seed = (hash ^ (r * 73856093) ^ (c * 19349663)) >>> 0;
        preencher = (seed % 3) === 0;
      }

      if (preencher) {
        ctx.fillRect(c * cell, r * cell, cell, cell);
      }
    }
  }
}

